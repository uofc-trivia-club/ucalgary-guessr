// Regenerate the bundled photo catalog after adding or moving photo assets.
// This writes SQL only; it never connects to the application's database.
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../public/assets/photos/", import.meta.url));
const { buildings } = JSON.parse(fs.readFileSync(new URL("../server/data/campus-buildings.json", import.meta.url), "utf8"));
// Pin registered IDs across filename/format changes so assigned challenges and
// scores continue to reference the same photo. New paths still get hashed IDs.
const stableIds = new Map(Object.entries(JSON.parse(fs.readFileSync(new URL("../server/data/photo-ids.json", import.meta.url), "utf8"))));
const stableOrder = new Map([...stableIds.values()].map((id, index) => [id, index]));
// Preserve all original outdoor answer coordinates, as well as their buildings.
const outdoorCoordinates = new Map([
  ["outdoors/EEEL-facing-ES.webp", [51.081080, -114.129440]],
  ["outdoors/MH-south.webp", [51.078570, -114.130450]],
  ["outdoors/EEEL-31st-terminal.webp", [51.081731, -114.129957]],
]);
function walk(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
    const full = path.join(directory, entry.name);
    if (entry.isSymbolicLink()) throw new Error("Photo symlinks are not supported: " + full);
    return entry.isDirectory() ? walk(full)
      : /\.(jpe?g|png|webp)$/i.test(entry.name) ? [path.relative(root, full).replaceAll("\\", "/")] : [];
  });
}
function answerBuilding(file) {
  let code = path.basename(file).match(/^([A-Za-z]+)(?=[\s.\-_(]|$)/)?.[1].toUpperCase();
  if (code === "EEL") code = "EEEL";
  const matches = buildings.filter(building => building.code === code);
  if (matches.length === 1) return matches[0];
  // Main-campus science photos (including Weekly interiors) resolve reused codes.
  if (/^(sciences|weekly-images)\//.test(file)) {
    const name = { SS: "Social Sciences", ST: "Science Theatres" }[code];
    const match = matches.find(building => building.name === name);
    if (match) return match;
  }
  throw new Error("Unknown or ambiguous building code for " + file + ": " + code);
}
const files = walk(root).sort();
for (const file of stableIds.keys()) if (!files.includes(file)) throw new Error("Update server/data/photo-ids.json for moved registered photo: " + file);
const photos = files.map(file => {
  const building = answerBuilding(file);
  const id = stableIds.get(file) ?? "photo-" + crypto.createHash("sha256").update(file).digest("hex").slice(0, 20);
  const [latitude, longitude] = outdoorCoordinates.get(file) ?? [building.latitude, building.longitude];
  return { id, file, pool: file.startsWith("weekly-images/") ? "weekly" : "standard", latitude, longitude, building };
}).sort((a, b) => (stableOrder.get(a.id) ?? Infinity) - (stableOrder.get(b.id) ?? Infinity) || a.file.localeCompare(b.file, "en"));
if (new Set(photos.map(photo => photo.id)).size !== photos.length) throw new Error("Duplicate photo IDs");
// Duplicate photos across pools defeat Weekly exclusivity even with different paths.
const weeklyHashes = new Set(photos.filter(photo => photo.pool === "weekly").map(photo => crypto.createHash("sha256").update(fs.readFileSync(path.join(root, photo.file))).digest("hex")));
for (const photo of photos.filter(photo => photo.pool !== "weekly")) {
  const hash = crypto.createHash("sha256").update(fs.readFileSync(path.join(root, photo.file))).digest("hex");
  if (weeklyHashes.has(hash)) throw new Error("Weekly-only content also appears outside weekly-images: " + photo.file);
}
const quote = value => typeof value === "number" ? String(value) : "'" + String(value).replaceAll("'", "''") + "'";
const columns = ["image_id", "image_path", "photo_pool", "answer_latitude", "answer_longitude", "answer_building_name", "answer_building_latitude", "answer_building_longitude"];
const values = photos.map(photo => "  (" + [photo.id, "/assets/photos/" + photo.file, photo.pool, photo.latitude, photo.longitude, photo.building.name, photo.building.latitude, photo.building.longitude].map(quote).join(", ") + ")");
const updates = columns.slice(1).map(column => "  " + column + " = excluded." + column).join(",\n");
const sql = "-- Generated by node scripts/generate-photo-seed.js; update server/data/photo-ids.json when moving registered photos.\n" +
  "-- Canonical names/centroids come from server/data/campus-buildings.json.\n" +
  "-- Only weekly-images photos enter the Weekly pool. Custom photo rows are preserved.\n\n" +
  "INSERT INTO photos (" + columns.join(", ") + ") VALUES\n" + values.join(",\n") +
  "\nON CONFLICT(image_id) DO UPDATE SET\n" + updates + ";\n";
fs.writeFileSync(new URL("../server/db/seed.sql", import.meta.url), sql);
console.log(JSON.stringify({ total: photos.length, dailyAndPlay: photos.filter(photo => photo.pool === "standard").length, weekly: photos.filter(photo => photo.pool === "weekly").length }));
